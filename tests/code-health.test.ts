import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { after, before, test } from 'node:test';
import { resolveConfig } from '../src/core/config.js';
import type { Entity, SoftwareGraph } from '../src/core/graph.js';
import { CODE_HEALTH_VERSION, matchSymbols } from '../src/analysis/metrics/analyzer.js';
import { spreadRank, type FileHealth, type RepositoryHealth } from '../src/analysis/metrics/health.js';
import { AnalysisCache } from '../src/pipeline/cache.js';
import { indexRepository } from '../src/pipeline/index.js';

let root: string, cacheDirectory: string;
const files: Record<string, string> = {
  'src/cart.ts': [
    'export class Cart {',
    '  add(item: Item) {',
    '    if (item.count > 0) {',
    '      this.items.push(item);',
    '    }',
    '  }',
    '}',
    'export function total(items: Item[], discount: number) {',
    '  let sum = 0;',
    '  for (const item of items) {',
    '    if (item.price > 0 && item.count > 0) {',
    '      sum += item.price * item.count;',
    '    }',
    '  }',
    '  return sum - discount;',
    '}',
    'export const save = useCallback(',
    '  (value: number) => {',
    '    if (value) {',
    '      return 1;',
    '    }',
    '    return 0;',
    '  },',
    '  [],',
    ');',
    'export interface Store { load(id: string): Item }',
  ].join('\n'),
  'src/cart.test.ts': "test('adds', () => {\n  for (const item of items) {\n    if (item) {\n      expect(item).toBeTruthy();\n    }\n  }\n});\n",
  'api/views.py': 'class Orders:\n    def list(self, request, page=1):\n        if page < 1:\n            return []\n        return [order for order in self.all() if order.visible]\n',
  'gen/api.pb.go': '// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage gen\n\nfunc Marshal(value int) int {\n\tif value > 0 {\n\t\treturn value\n\t}\n\treturn 0\n}\n',
};
const write = async (file: string, content: string) => { await mkdir(path.dirname(path.join(root, file)), { recursive: true }); await writeFile(path.join(root, file), content); };
const index = async (options: { cache?: AnalysisCache; revision?: string } = {}) => indexRepository(root, { config: await resolveConfig(root, { repository: { name: 'health' }, applications: [{ name: 'app', path: '.' }] }), ...options });
const symbol = (graph: SoftwareGraph, name: string) => graph.entities.find(entity => entity.name === name && entity.type !== 'file')!;
const file = (graph: SoftwareGraph, relative: string) => graph.entities.find(entity => entity.type === 'file' && entity.path === relative)!;

before(async () => {
  root = await mkdtemp(path.join(tmpdir(), 'codiluce-health-'));
  cacheDirectory = await mkdtemp(path.join(tmpdir(), 'codiluce-health-cache-'));
  for (const [name, content] of Object.entries(files)) await write(name, content);
});
after(async () => { await rm(root, { recursive: true, force: true }); await rm(cacheDirectory, { recursive: true, force: true }); });

test('functions are measured on the symbols they are', async () => {
  const graph = await index();
  const metrics = (name: string) => { const { codeLines, complexity, nesting, parameters } = symbol(graph, name).metrics ?? {}; return { codeLines, complexity, nesting, parameters }; };
  assert.deepEqual(metrics('add'), { codeLines: 3, complexity: 2, nesting: 1, parameters: 1 });
  assert.deepEqual(metrics('total'), { codeLines: 6, complexity: 4, nesting: 2, parameters: 2 });
  // The declaration ends after the callback (`[],\n);`): matched by name inside it.
  assert.deepEqual(metrics('save'), { codeLines: 4, complexity: 2, nesting: 1, parameters: 1 });
  // `self` is not a parameter; comprehension clauses are not decisions.
  assert.deepEqual(metrics('list'), { codeLines: 4, complexity: 2, nesting: 1, parameters: 2 });
  // A class is not a function; an interface's signatures have no body.
  assert.equal(symbol(graph, 'Cart').metrics?.complexity, undefined);
});

test('files list their worst functions and say why they were not measured', async () => {
  const graph = await index();
  const cart = file(graph, 'src/cart.ts');
  assert.equal(cart.metrics?.functions, 3);
  assert.equal(cart.metrics?.maxComplexity, 4);
  assert.equal(cart.metrics?.maxNesting, 2);
  assert.equal(cart.metrics?.codeLines, 16);
  const worst = (cart.metadata.health as Extract<FileHealth, { worst: unknown }>).worst;
  assert.deepEqual(worst.map(item => [item.name, item.complexity, item.symbol === symbol(graph, item.name.split('.').at(-1)!).id]), [['total', 4, true], ['save', 2, true], ['Cart.add', 2, true]]);
  // A test's callback is a function of its own, not a symbol.
  assert.deepEqual((file(graph, 'src/cart.test.ts').metadata.health as Extract<FileHealth, { worst: unknown }>).worst.map(item => [item.name, item.symbol]), [['test callback', undefined]]);
  const generated = file(graph, 'gen/api.pb.go');
  assert.match((generated.metadata.health as Extract<FileHealth, { skipped: string }>).skipped, /generated/i);
  assert.equal(generated.metrics?.codeLines, undefined);
  assert.equal(symbol(graph, 'Marshal')?.metrics?.complexity, undefined);
});

test('the repository spread compares functions with their language, outside tests', async () => {
  const graph = await index();
  const health = graph.entities.find(entity => entity.type === 'repository')!.metadata.codeHealth as RepositoryHealth;
  assert.equal(health.version, CODE_HEALTH_VERSION);
  assert.deepEqual([health.files, health.skipped], [3, 1]);
  assert.deepEqual(Object.keys(health.languages), ['python', 'typescript']);
  // cart.test.ts is not counted: three TypeScript functions, all in cart.ts.
  assert.equal(health.languages.typescript!.functions, 3);
  assert.deepEqual(health.languages.typescript!.complexity, [[2, 2], [4, 1]]);
  assert.equal(spreadRank(health.languages.typescript!.complexity, 4), 2 / 3);
  assert.equal(spreadRank(health.languages.typescript!.complexity, 2), 0);
  assert.equal(graph.run.analyzerVersions['code-health'], CODE_HEALTH_VERSION);
});

test('a history snapshot measures as the working tree does', async () => {
  const [working, revision] = [await index(), await index({ revision: 'a'.repeat(40) })];
  const health = (graph: SoftwareGraph) => graph.entities.map(entity => [entity.id, entity.metrics, entity.metadata.health, entity.metadata.codeHealth]);
  assert.deepEqual(health(revision), health(working));
});

test('measurements are kept by content and reused', async () => {
  const cache = new AnalysisCache(cacheDirectory);
  const first = await index({ cache });
  const stored = () => cache.kept<[string, unknown][]>('code-health', 'repository', { analyzer: CODE_HEALTH_VERSION })!.map(([key]) => key);
  const keys = stored();
  assert.equal(keys.length, 4);
  const again = await index({ cache });
  assert.deepEqual(again.entities.map(entity => entity.metrics), first.entities.map(entity => entity.metrics));
  assert.deepEqual(stored(), keys);
  await write('api/views.py', `${files['api/views.py']}    def count(self):\n        return len(self.all())\n`);
  const changed = await index({ cache });
  assert.equal(symbol(changed, 'count').metrics?.complexity, 1);
  assert.equal(stored().filter(key => !keys.includes(key)).length, 1);
  await write('api/views.py', files['api/views.py']!);
});

test('symbols match the function ending where they end, by name first', () => {
  const entity = (name: string, startLine: number, endLine: number) => ({ id: name, type: 'function', name, metadata: {}, evidence: [], sourceRange: { startLine, endLine } }) as Entity;
  const fn = (name: string, startLine: number, endLine: number) => ({ name, startLine, endLine, length: 1, complexity: 1, nesting: 0, parameters: 0 });
  const outer = fn('outer', 2, 9), inner = fn('outer.inner', 4, 9), decorated = fn('Api.get', 12, 15), other = fn('other', 20, 22);
  const matched = matchSymbols([entity('inner', 4, 9), entity('outer', 1, 9), entity('get', 11, 15), entity('missing', 30, 31)], [outer, inner, decorated, other]);
  assert.deepEqual([...matched].map(([item, entities]) => [item.name, entities.map(each => each.name)]), [['outer.inner', ['inner']], ['outer', ['outer']], ['Api.get', ['get']]]);
});
