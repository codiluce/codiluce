import assert from 'node:assert/strict';
import { test } from 'node:test';
import { cp, mkdir, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { indexRepository } from '../../src/pipeline/index.js';
import { GraphStore } from '../../src/storage/sqlite.js';
import { ProjectionService } from '../../src/projection/service.js';
import { AtlasStore } from '../lib/store';
import { ServiceApi, RecordingNavigator } from './service-api';

test('map preferences replace the scene, keep hidden selections inspectable, reveal, undo, and survive reload', async t => {
  const root = await mkdtemp(path.join(tmpdir(), 'codiluce-map-store-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await cp(fileURLToPath(new URL('../../tests/fixtures/repository', import.meta.url)), root, { recursive: true });
  const stateDirectory = path.join(root, '.codiluce'); await mkdir(stateDirectory);
  const graph = await indexRepository(root);
  const store = new GraphStore(':memory:'); store.save(graph); t.after(() => store.close());
  const projection = new ProjectionService(store, { root, stateDirectory });
  const atlas = new AtlasStore(new ServiceApi(store, projection)); t.after(() => atlas.dispose());
  const navigator = new RecordingNavigator(); atlas.navigator = navigator;
  const entity = (relative: string, type = 'file') => graph.entities.find(row => row.path === relative && row.type === type)!;
  await atlas.init();
  const folder = projection.locate(entity('backend/app', 'directory').id).node;
  await atlas.select(folder.id); await atlas.hideFromMap(folder);
  assert.ok(!atlas.scene.nodes.has(folder.id));
  assert.equal(atlas.getState().selection?.node?.hidden, true);
  const file = projection.locate(entity('backend/app/Services/AuthService.php').id).node;
  const flights = navigator.flights.length;
  await atlas.select(file.id);
  assert.equal(navigator.flights.length, flights, 'hidden selections do not fly to zero-size rectangles');
  assert.ok(!atlas.scene.nodes.has(file.id), 'search does not silently put hidden nodes back');
  await atlas.revealOnMap(file);
  assert.ok(atlas.scene.nodes.has(file.id));
  assert.ok(!atlas.scene.nodes.has(entity('backend/app/Http/Controllers/AuthController.php').id));
  await atlas.hideFromMap(atlas.getState().selection!.node!);
  await atlas.undoMapVisibility();
  assert.ok(atlas.scene.nodes.has(file.id), 'Undo also restores a previous visible exception');
  await atlas.changeMapVisibility({ action: 'conceal', path: file.path! });
  assert.ok(!atlas.scene.nodes.has(file.id));
  await atlas.reload();
  assert.equal(atlas.getState().selection?.node?.hidden, true);
  assert.equal(atlas.getState().mapVisibility.busy, false);
});
